"""Build a tar.gz bundle of a run's key files for sharing / review.

Public endpoint serves this; users hit "Download bundle" on result page →
gets a self-contained tarball they can email / 飞书 / send to collaborators
(e.g. 杨博) for evaluator review without needing server access.

Bundle layout:
    <run_id>/
    ├── README.md            # auto: scoring summary + bundle layout
    ├── agent_run/           # workdir 关键 input/output 文件（in/out/dat/log/json/txt）
    ├── ground_truth/        # bench 题目 JSON + gt_data/<id>/* (dos_reference.dat 等)
    └── report.json          # evaluator 评分结果

Exclusions (size + irrelevance for review):
    - tmp* / *.save / pseudos / __pycache__ 整个目录
    - wfc*.dat / charge-density* / spin-density* / paw*.dat 文件
    - 单文件 > 5 MB（bands.dat for big systems can blow this — skipped）
"""
from __future__ import annotations

import fnmatch
import io
import json
import tarfile
import time
from pathlib import Path
from typing import Optional

# --- inclusion / exclusion rules ---

_INCLUDE_EXTS = {".in", ".out", ".log", ".dat", ".json", ".txt", ".md", ".err"}
_MAX_FILE_BYTES = 5 * 1024 * 1024
_EXCLUDE_DIR_PATTERNS = ("tmp", "tmp_*", "*.save", "pseudos", "__pycache__")
_EXCLUDE_FILE_PATTERNS = ("wfc*.dat", "charge-density*", "spin-density*", "paw*.dat")


def _dir_excluded(name: str) -> bool:
    return any(fnmatch.fnmatch(name, p) for p in _EXCLUDE_DIR_PATTERNS)


def _file_excluded(name: str) -> bool:
    return any(fnmatch.fnmatch(name, p) for p in _EXCLUDE_FILE_PATTERNS)


def _collect_workdir_files(workdir: Path) -> list[tuple[Path, str]]:
    """Walk workdir; return [(abs_path, relative_path)] for files matching include rules."""
    out: list[tuple[Path, str]] = []
    if not workdir.exists() or not workdir.is_dir():
        return out
    for p in workdir.rglob("*"):
        rel = p.relative_to(workdir)
        if any(_dir_excluded(part) for part in rel.parts):
            continue
        if not p.is_file():
            continue
        if p.suffix.lower() not in _INCLUDE_EXTS:
            continue
        if _file_excluded(p.name):
            continue
        try:
            if p.stat().st_size > _MAX_FILE_BYTES:
                continue
        except OSError:
            continue
        out.append((p, str(rel)))
    out.sort(key=lambda x: x[1])
    return out


def _build_readme(run_id: str, task_id: Optional[str], run_dir: Path) -> str:
    lines: list[str] = [
        f"# Run bundle: {run_id}",
        "",
        f"- run_id: `{run_id}`",
        f"- task_id: `{task_id or '(custom run, no task_id)'}`",
        f"- run_dir on server: `{run_dir}`",
        f"- bundled at: {time.strftime('%Y-%m-%d %H:%M:%S UTC', time.gmtime())}",
        "",
    ]
    report_path = run_dir / "report.json"
    if report_path.exists():
        try:
            d = json.loads(report_path.read_text(encoding="utf-8"))
            lines += [
                "## Scoring summary",
                "",
                f"- model: `{d.get('model', '?')}`",
                f"- total_score: **{d.get('total_score')}**",
                f"- solver_status: `{d.get('solver_status', '?')}`",
                f"- wall_time_sec: {d.get('solver_wall_clock_sec') or d.get('wall_time_sec', '?')}",
                "",
            ]
            pfs = d.get("per_field_scores") or {}
            if pfs:
                lines += [
                    "### per_field_scores",
                    "",
                    "| field | score |",
                    "|---|---|",
                ]
                for k, v in pfs.items():
                    lines.append(f"| {k} | {v} |")
                lines.append("")
            af = d.get("audit_flags") or {}
            if af:
                lines += [
                    "### audit_flags",
                    "",
                    "| flag | pass |",
                    "|---|---|",
                ]
                for k, v in af.items():
                    lines.append(f"| {k} | {'✓' if v else '✗'} |")
                lines.append("")
        except (OSError, json.JSONDecodeError):
            pass
    lines += [
        "## Bundle layout",
        "",
        "- `agent_run/` — agent workdir 关键 input/output 文件（已剔除 tmp_*/wfc*/charge_density* 等大文件，单文件上限 5 MB）",
        "- `ground_truth/` — bench 题目 JSON + GT 数据文件（dos_reference.dat 等）；custom run 时此目录可能为空",
        "- `report.json` — evaluator 评分 + extracted_fields 完整结果",
        "",
        "Generated by web-fresh `/api/runs/<run_id>/case_bundle` endpoint.",
    ]
    return "\n".join(lines) + "\n"


def build_bundle(
    *,
    run_id: str,
    run_dir: Path,
    task_id: Optional[str],
    bench_questions_dir: Optional[Path],
) -> bytes:
    """Build tar.gz in memory; return bytes (caller streams to client).

    Always packs README.md (auto) + report.json (if exists) + agent_run/ (workdir).
    For bench runs additionally packs ground_truth/<task_id>.json + gt_data/<task_id>/*.
    """
    buf = io.BytesIO()
    bundle_root = run_id

    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        # 1. agent_run/: workdir key files
        workdir = run_dir / "workdir"
        for abs_path, rel_path in _collect_workdir_files(workdir):
            arcname = f"{bundle_root}/agent_run/{rel_path}"
            try:
                tar.add(abs_path, arcname=arcname, recursive=False)
            except (OSError, ValueError):
                pass

        # 2. report.json
        report_path = run_dir / "report.json"
        if report_path.exists():
            try:
                tar.add(report_path, arcname=f"{bundle_root}/report.json", recursive=False)
            except (OSError, ValueError):
                pass

        # 3. ground_truth/ — bench mode only
        if task_id and bench_questions_dir:
            parts = task_id.split("_")
            if len(parts) >= 3:
                subdir = f"{parts[0]}_{parts[1]}"
                task_json = bench_questions_dir / subdir / f"{task_id}.json"
                if task_json.exists():
                    try:
                        tar.add(task_json, arcname=f"{bundle_root}/ground_truth/{task_id}.json",
                                recursive=False)
                    except (OSError, ValueError):
                        pass
                gt_data_dir = bench_questions_dir / subdir / "gt_data" / task_id
                if gt_data_dir.exists() and gt_data_dir.is_dir():
                    for p in sorted(gt_data_dir.iterdir()):
                        if not p.is_file():
                            continue
                        try:
                            if p.stat().st_size > _MAX_FILE_BYTES:
                                continue
                            tar.add(p, arcname=f"{bundle_root}/ground_truth/{p.name}",
                                    recursive=False)
                        except (OSError, ValueError):
                            pass

        # 4. README.md (auto-generated, always last so user sees it on top in many UIs)
        readme = _build_readme(run_id, task_id, run_dir)
        readme_bytes = readme.encode("utf-8")
        info = tarfile.TarInfo(name=f"{bundle_root}/README.md")
        info.size = len(readme_bytes)
        info.mtime = int(time.time())
        info.mode = 0o644
        tar.addfile(info, io.BytesIO(readme_bytes))

    return buf.getvalue()
